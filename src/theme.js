export const themePalettes = Object.entries(palettes).map(([id, palette]) => ({ id, ...palette }));

export function getThemeId(theme) {
  if (theme === 'light') return 'forest';
  if (theme === 'dark') return 'midnight';
  return Object.prototype.hasOwnProperty.call(palettes, theme) ? theme : 'forest';
}

export function getTheme(theme) {
  return palettes[getThemeId(theme)];
}
